export interface StickerStatItem {
  sticker: RetroSticker;
  count: number;
  percentage: number;
  rank: number;
}

/**
 * Calculates popularity statistics for all stickers based on guestbook entries.
 * Combines dynamic usage in guestbook entries with baseline counts so statistics
 * remain rich, informative, and immediately dynamic.
 */
export function calculateStickerStats(
  entries: { sticker?: RetroSticker }[],
  stickers: RetroSticker[] = RETRO_STICKERS
): { stats: StickerStatItem[]; totalUsage: number; topSticker: RetroSticker | null } {
  // Count real usage in entries
  const realCounts: Record<string, number> = {};
  let totalEntriesWithStickers = 0;

  entries.forEach((e) => {
    if (e.sticker?.id) {
      realCounts[e.sticker.id] = (realCounts[e.sticker.id] || 0) + 1;
      totalEntriesWithStickers += 1;
    }
  });

  // Calculate combined count (basePopularity + real dynamic count * 3 to strongly boost real user interactions)
  const list = stickers.map((sticker) => {
    const realCount = realCounts[sticker.id] || 0;
    const base = sticker.basePopularity || 10;
    const totalCount = base + realCount * 4;
    return {
      sticker,
      realCount,
      totalCount
    };
  });

  // Sort descending by totalCount
  list.sort((a, b) => b.totalCount - a.totalCount);

  const grandTotal = list.reduce((sum, item) => sum + item.totalCount, 0);

  const stats: StickerStatItem[] = list.map((item, idx) => ({
    sticker: item.sticker,
    count: item.totalCount,
    percentage: grandTotal > 0 ? Math.round((item.totalCount / grandTotal) * 100) : 0,
    rank: idx + 1
  }));

  return {
    stats,
    totalUsage: grandTotal,
    topSticker: stats[0]?.sticker || null
  };
}
